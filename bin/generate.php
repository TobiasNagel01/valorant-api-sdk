/** Path placeholders whose PHP variable name should differ from the placeholder. */
const PATH_VAR_OVERRIDES = ['player' => 'playerId', 'player_id' => 'playerId'];

/** Path parameters that carry a default. */
const PATH_DEFAULTS = ['StoreFeatured' => ['version' => "'v1'"], 'StoreOffers' => ['version' => "'v1'"]];

/** @var array<string, array{fixture: string, dto: ?string, args: array<int, string>}> $manifest */
$manifest = [];

foreach (OPERATIONS as $operationId => [$group, $className]) {
    $operation = $operations[$operationId];
    $namespace = NS.'\\Requests\\'.$group;
    $path = (string) $operation['__path'];
    $httpMethod = (string) $operation['__method'];

    $imports = [
        'Saloon\\Enums\\Method',
        'Saloon\\Http\\Request',
        NS.'\\Requests\\Concerns\\NormalisesParameters',
    ];

    /** @var array<string, array<string, mixed>> $paramsByName */
    $paramsByName = [];

    foreach ($operation['parameters'] ?? [] as $parameter) {
        $paramsByName[(string) $parameter['name']] = $parameter;
    }

    preg_match_all('/\{([^}]+)\}/', $path, $matches);
    $placeholders = $matches[1];

    $unmatchedPathParams = array_values(array_filter(
        $paramsByName,
        static fn (array $parameter): bool => ($parameter['in'] ?? null) === 'path'
            && ! in_array((string) $parameter['name'], $placeholders, true),
    ));

    $head = [];
    $tail = [];
    $docLines = [];
    $endpoint = $path;
    $manifestHead = [];
    $manifestTail = [];

    // Path parameters, in the order they appear in the URL.
    foreach ($placeholders as $placeholder) {
        $parameter = $paramsByName[$placeholder] ?? array_shift($unmatchedPathParams);
        $variable = PATH_VAR_OVERRIDES[$placeholder] ?? camel($placeholder);
        $default = PATH_DEFAULTS[$operationId][$placeholder] ?? null;

        if (isset(PARAM_OVERRIDES[$placeholder])) {
            $type = PARAM_OVERRIDES[$placeholder]['type'];
            $imports[] = PARAM_OVERRIDES[$placeholder]['enum'];
            $argument = $placeholder === 'affinity' ? "'eu'" : "'pc'";
        } else {
            $schemaType = $parameter['schema']['type'] ?? 'string';
            $type = scalarPhpType(is_array($schemaType) ? ($schemaType[0] ?? 'string') : $schemaType);
            $argument = $default ?? ($type === 'int' ? '1' : "'sample'");
        }

        $default === null ? $manifestHead[] = $argument : $manifestTail[] = $argument;

        $description = trim((string) ($parameter['description'] ?? ''));

        if ($description !== '') {
            $docLines[] = '     * @param  '.docType($type).'  $'.$variable.'  '.$description;
        }

        $line = '        private readonly '.$type.' $'.$variable.($default === null ? ',' : ' = '.$default.',');
        $default === null ? $head[] = $line : $tail[] = $line;

        $endpoint = str_replace('{'.$placeholder.'}', "'.\$this->segment(\$this->".$variable.").'", $endpoint);
    }

    // Request body.
    $bodyRef = $operation['requestBody']['content']['application/json']['schema']['$ref'] ?? null;

    if (is_string($bodyRef)) {
        $bodyFqcn = schemaClass(refName($bodyRef), $schemas);
        $imports[] = $bodyFqcn;
        $imports[] = 'Saloon\\Contracts\\Body\\HasBody';
        $imports[] = 'Saloon\\Traits\\Body\\HasJsonBody';
        $imports[] = NS.'\\Requests\\Concerns\\SendsJsonPayload';
        $head[] = '        private readonly '.shortClass($bodyFqcn).' $payload,';
        $manifestHead[] = '__PAYLOAD__';
        $docLines[] = '     * @param  '.shortClass($bodyFqcn).'  $payload  The request body sent as JSON.';
    }

    // Query parameters.
    $queryLines = [];

    foreach ($paramsByName as $parameterName => $parameter) {
        if (($parameter['in'] ?? null) !== 'query') {
            continue;
        }

        $variable = camel($parameterName);
        $resolved = resolveType($parameter['schema'] ?? [], $schemas, true);
        $imports = array_merge($imports, $resolved['imports']);

        $description = trim((string) ($parameter['description'] ?? ''));

        // Only worth a docblock line when it adds something the signature does not already say.
        if ($description !== '' || $resolved['doc'] !== null) {
            $docLines[] = '     * @param  '.($resolved['doc'] ?? docType($resolved['php'])).'  $'.$variable
                .($description === '' ? '' : '  '.$description);
        }

        $tail[] = '        private readonly '.$resolved['php'].' $'.$variable.' = null,';
        $queryLines[] = "            '".$parameterName."' => \$this->".$variable.',';
    }

    // Response DTO: whatever the envelope wraps, or the schema itself when it is not an envelope.
    $status = SUCCESS_STATUS[$operationId] ?? '200';
    $responseRef = $operation['responses'][$status]['content']['application/json']['schema']['$ref'] ?? null;
    $dtoFqcn = null;
    $isCollection = false;
    $isEnveloped = false;

    if (is_string($responseRef) && ! in_array($operationId, NO_DTO_OPERATIONS, true)) {
        $responseName = refName($responseRef);
        $envelope = envelopeOf($responseName, $schemas);

        if ($envelope === null) {
            $dtoFqcn = schemaClass($responseName, $schemas);
        } elseif ($envelope['item'] !== null && ! isset(UNION_SCHEMAS[$envelope['item']])) {
            $dtoFqcn = schemaClass($envelope['item'], $schemas);
            $isCollection = $envelope['collection'];
            $isEnveloped = true;
        }
    }

    if ($dtoFqcn !== null) {
        $imports[] = $dtoFqcn;
        $imports[] = 'Saloon\\Http\\Response';

        if ($isEnveloped) {
            $imports[] = NS.'\\Requests\\Concerns\\ReadsResponseData';
        }

        if ($isCollection) {
            $imports[] = 'Illuminate\\Support\\Collection';
        }
    }

    $params = array_merge($head, $tail);
    $summary = trim((string) ($operation['summary'] ?? $className));

    $classDoc = "/**\n * ".$summary."\n *\n * @see ".DOC_LINKS[$group]."\n *\n * ".MARKER."\n */\n";

    $body = "<?php\n\nnamespace ".$namespace.";\n\n"
        .renderImports($imports, $namespace)
        .$classDoc
        .'class '.$className.' extends Request'.($bodyRef === null ? '' : ' implements HasBody')."\n{\n"
        ."    use NormalisesParameters;\n"
        .($isEnveloped ? "    use ReadsResponseData;\n" : '')
        .($bodyRef === null ? '' : "    use HasJsonBody;\n    use SendsJsonPayload;\n")
        ."\n    protected Method \$method = Method::".$httpMethod.";\n";

    if ($params !== []) {
        $body .= "\n";

        if ($docLines !== []) {
            $body .= "    /**\n".implode("\n", $docLines)."\n     */\n";
        }

        $body .= "    public function __construct(\n".implode("\n", $params)."\n    ) {\n    }\n";
    }

    // A path ending in a placeholder would otherwise close with a dangling empty string.
    $expression = "'".$endpoint."'";
    $expression = str_ends_with($expression, ".''") ? substr($expression, 0, -3) : $expression;

    $body .= "\n    public function resolveEndpoint(): string\n    {\n        return ".$expression.";\n    }\n";

    if ($queryLines !== []) {
        $body .= "\n    /**\n     * @return array<string, mixed>\n     */\n"
            ."    protected function defaultQuery(): array\n    {\n"
            ."        return \$this->filterQuery([\n".implode("\n", $queryLines)."\n        ]);\n    }\n";
    }

    if ($bodyRef !== null) {
        $body .= "\n    /**\n     * @return array<string, mixed>\n     */\n"
            ."    protected function defaultBody(): array\n    {\n"
            ."        return \$this->payloadToBody(\$this->payload);\n    }\n";
    }

    if ($dtoFqcn !== null) {
        $short = shortClass($dtoFqcn);

        if ($isCollection) {
            $body .= "\n    /**\n     * @return Collection<int, ".$short.">\n     */\n"
                ."    public function createDtoFromResponse(Response \$response): Collection\n    {\n"
                .'        return collect($this->data($response))->map(static fn (mixed $item): '.$short.' => '.$short."::from(\$item));\n    }\n";
        } else {
            $source = $isEnveloped ? '$this->data($response)' : '$response->json()';

            $body .= "\n    public function createDtoFromResponse(Response \$response): ".$short."\n    {\n"
                .'        return '.$short.'::from('.$source.");\n    }\n";
        }
    }

    $body .= "}\n";

    writeFile(ROOT.'/src/Requests/'.$group.'/'.$className.'.php', $body);
    $written['request']++;

    $manifest[$operationId] = [
        'group' => $group,
        'request' => $namespace.'\\'.$className,
        'dto' => $dtoFqcn,
        'collection' => $isCollection,
        'args' => array_merge($manifestHead, $manifestTail),
        'body' => is_string($bodyRef) ? refName($bodyRef) : null,
    ];
}

