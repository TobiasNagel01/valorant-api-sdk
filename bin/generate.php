/**
 * @param  array<string, true>  $found
 */
function collectRefs(mixed $node, array &$found): void
{
    if (! is_array($node)) {
        return;
    }

    foreach ($node as $key => $value) {
        if ($key === '$ref' && is_string($value) && str_starts_with($value, '#/components/schemas/')) {
            $found[substr($value, strlen('#/components/schemas/'))] = true;

            continue;
        }

        collectRefs($value, $found);
    }
}

$frontier = [];
collectRefs($operations, $frontier);

// Seed the closure with the payload each envelope wraps, not the envelope itself.
foreach (array_keys($frontier) as $rootName) {
    $envelope = envelopeOf($rootName, $schemas);

    if ($envelope === null) {
        continue;
    }

    unset($frontier[$rootName]);

    if ($envelope['item'] !== null && ! isset(UNION_SCHEMAS[$envelope['item']])) {
        $frontier[$envelope['item']] = true;
    }

    if ($envelope['results'] !== null) {
        $frontier[$envelope['results']] = true;
    }
}

/** @var array<string, true> $reachable */
$reachable = [];

while ($frontier !== []) {
    $name = array_key_first($frontier);
    unset($frontier[$name]);

    if (isset($reachable[$name]) || ! isset($schemas[$name])) {
        continue;
    }

    $reachable[$name] = true;

    $nested = [];
    collectRefs($schemas[$name], $nested);

    foreach ($nested as $child => $_) {
        if (! isset($reachable[$child])) {
            $frontier[$child] = true;
        }
    }
}

$reachableNames = array_keys($reachable);
sort($reachableNames);

