/** @var array<string, int> $written */
$written = ['dto' => 0, 'enum' => 0, 'request' => 0, 'fixture' => 0];

/** @var array<string, true> $writtenPaths */
$writtenPaths = [];

function writeFile(string $path, string $contents): void
{
    global $writtenPaths;

    $directory = dirname($path);

    if (! is_dir($directory)) {
        mkdir($directory, 0o755, true);
    }

    file_put_contents($path, $contents);
    $writtenPaths[realpath($path) ?: $path] = true;
}

function pathForClass(string $fqcn): string
{
    return ROOT.'/src/'.str_replace('\\', '/', substr($fqcn, strlen(NS) + 1)).'.php';
}

/**
 * @param  array<int, string>  $imports
 */
function renderImports(array $imports, string $currentNamespace): string
{
    $imports = array_values(array_unique(array_filter(
        $imports,
        static fn (string $import): bool => namespaceOf($import) !== $currentNamespace,
    )));

    sort($imports);

    if ($imports === []) {
        return '';
    }

    return implode("\n", array_map(static fn (string $import): string => 'use '.$import.';', $imports))."\n\n";
}

// ---------------------------------------------------------------------------------------------
// Enums
// ---------------------------------------------------------------------------------------------

foreach ($reachableNames as $name) {
    if (! isEnumSchema($name, $schemas)) {
        continue;
    }

    $fqcn = schemaClass($name, $schemas);
    $cases = [];

    foreach ($schemas[$name]['enum'] as $value) {
        $value = (string) $value;
        $case = ENUM_CASE_OVERRIDES[$name][$value] ?? studly($value);
        $cases[] = '    case '.$case." = '".$value."';";
    }

    $body = "<?php\n\nnamespace ".namespaceOf($fqcn).";\n\n"
        ."/**\n * ".MARKER."\n *\n * Generated from the `".$name."` schema in openapi.json. Do not edit by hand.\n */\n"
        .'enum '.shortClass($fqcn).": string\n{\n"
        .implode("\n", $cases)
        ."\n}\n";

    writeFile(pathForClass($fqcn), $body);
    $written['enum']++;
}

// ---------------------------------------------------------------------------------------------
// DTOs
// ---------------------------------------------------------------------------------------------

foreach ($reachableNames as $name) {
    if (isEnumSchema($name, $schemas) || isset(UNION_SCHEMAS[$name])) {
        continue;
    }

    $schema = $schemas[$name];
    $fqcn = schemaClass($name, $schemas);
    $namespace = namespaceOf($fqcn);

    $required = $schema['required'] ?? [];
    $imports = ['Spatie\\LaravelData\\Data'];
    $docLines = [];
    $head = [];
    $tail = [];

    foreach ($schema['properties'] ?? [] as $propertyName => $property) {
        $isRequired = in_array($propertyName, $required, true);
        $resolved = resolveType($property, $schemas, ! $isRequired);
        $imports = array_merge($imports, $resolved['imports']);

        $phpName = isValidIdentifier($propertyName) ? $propertyName : safePropertyName($propertyName);

        $lines = [];

        if ($phpName !== $propertyName) {
            $imports[] = 'Spatie\\LaravelData\\Attributes\\MapInputName';
            $lines[] = "        #[MapInputName('".$propertyName."')]";
        }

        foreach ($resolved['attributes'] as $attribute) {
            $lines[] = '        '.$attribute;
        }

        $lines[] = '        public '.$resolved['php'].' $'.$phpName.($isRequired ? ',' : ' = null,');

        if ($resolved['doc'] !== null) {
            $docLines[] = '     * @param  '.$resolved['doc'].'  $'.$phpName;
        }

        // Promoted properties with defaults must come last.
        if ($isRequired) {
            $head[] = implode("\n", $lines);
        } else {
            $tail[] = implode("\n", $lines);
        }
    }

    $params = array_merge($head, $tail);

    $docblock = $docLines === []
        ? ''
        : "    /**\n".implode("\n", $docLines)."\n     */\n";

    $constructor = $params === []
        ? "    public function __construct()\n    {\n    }\n"
        : $docblock."    public function __construct(\n".implode("\n", $params)."\n    ) {\n    }\n";

    $body = "<?php\n\nnamespace ".$namespace.";\n\n"
        .renderImports($imports, $namespace)
        ."/**\n * ".MARKER."\n *\n * Generated from the `".$name."` schema in openapi.json. Do not edit by hand.\n */\n"
        .'final class '.shortClass($fqcn)." extends Data\n{\n"
        .$constructor
        ."}\n";

    writeFile(pathForClass($fqcn), $body);
    $written['dto']++;
}

