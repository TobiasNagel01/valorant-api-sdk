// Type resolution
// ---------------------------------------------------------------------------------------------

function scalarPhpType(?string $type): string
{
    return match ($type) {
        'integer' => 'int',
        'number' => 'float',
        'boolean' => 'bool',
        'string' => 'string',
        default => 'mixed',
    };
}

function applyNullable(string $type, bool $nullable): string
{
    if (! $nullable || $type === 'mixed') {
        return $type;
    }

    return str_contains($type, '|') ? $type.'|null' : '?'.$type;
}

/** PHPDoc prefers the `X|null` union form over the `?X` shorthand. */
function docType(string $type): string
{
    return str_starts_with($type, '?') ? substr($type, 1).'|null' : $type;
}

function refName(string $ref): string
{
    return substr($ref, strlen('#/components/schemas/'));
}

/**
 * Recognises a response envelope: a schema that exists only to wrap the payload in `data`, beside
 * the echoed HTTP `status` and, on paginated endpoints, a `results` object.
 *
 * Envelopes are not generated. Requests return what the envelope wraps, and the pagination object
 * is reachable from the response via `ValorantApiResponse::pagination()`.
 *
 * @return array{item: ?string, collection: bool, results: ?string}|null
 */
function envelopeOf(string $name, array $schemas): ?array
{
    $properties = $schemas[$name]['properties'] ?? null;

    if (! is_array($properties) || ! isset($properties['data'])) {
        return null;
    }

    if (array_diff(array_keys($properties), ['data', 'status', 'results']) !== []) {
        return null;
    }

    $data = $properties['data'];
    $collection = ($data['type'] ?? null) === 'array';
    $ref = $collection ? ($data['items']['$ref'] ?? null) : ($data['$ref'] ?? null);
    $results = $properties['results']['$ref'] ?? null;

    return [
        'item' => is_string($ref) ? refName($ref) : null,
        'collection' => $collection,
        'results' => is_string($results) ? refName($results) : null,
    ];
}

/**
 * Maps one property schema onto a PHP type.
 *
 * @return array{php: string, doc: ?string, imports: array<int, string>, attributes: array<int, string>}
 */
function resolveType(array $property, array $schemas, bool $forceNullable = false): array
{
    $imports = [];
    $attributes = [];

    // The spec expresses "nullable object" as oneOf: [{type: null}, {$ref: …}].
    if (isset($property['oneOf'])) {
        $ref = null;

        foreach ($property['oneOf'] as $variant) {
            if (isset($variant['$ref'])) {
                $ref = refName($variant['$ref']);
            }
        }

        if ($ref !== null) {
            $fqcn = schemaClass($ref, $schemas);

            return ['php' => applyNullable(shortClass($fqcn), true), 'doc' => null, 'imports' => [$fqcn], 'attributes' => []];
        }

        return ['php' => 'mixed', 'doc' => null, 'imports' => [], 'attributes' => []];
    }

    if (isset($property['$ref'])) {
        $ref = refName($property['$ref']);

        if (isset(UNION_SCHEMAS[$ref])) {
            $union = UNION_SCHEMAS[$ref];

            return [
                'php' => applyNullable($union['php'], $forceNullable),
                'doc' => $union['php'] === $union['doc'] ? null : docType(applyNullable($union['doc'], $forceNullable)),
                'imports' => [],
                'attributes' => [],
            ];
        }

        $fqcn = schemaClass($ref, $schemas);

        return ['php' => applyNullable(shortClass($fqcn), $forceNullable), 'doc' => null, 'imports' => [$fqcn], 'attributes' => []];
    }

    $types = $property['type'] ?? null;

    if ($types === null) {
        return ['php' => 'mixed', 'doc' => null, 'imports' => [], 'attributes' => []];
    }

    $types = (array) $types;
    $nullable = $forceNullable || in_array('null', $types, true);
    $base = null;

    foreach ($types as $type) {
        if ($type !== 'null') {
            $base = (string) $type;

            break;
        }
    }

    if ($base === 'array') {
        $items = $property['items'] ?? [];
        $doc = 'array<int, mixed>';

        if (isset($items['$ref'])) {
            $ref = refName($items['$ref']);
            $fqcn = schemaClass($ref, $schemas);
            $short = shortClass($fqcn);
            $imports[] = $fqcn;
            $doc = 'array<int, '.$short.'>';

            if (isEnumSchema($ref, $schemas)) {
                $imports[] = 'Spatie\\LaravelData\\Attributes\\WithCast';
                $imports[] = NS.'\\Casts\\EnumArrayCast';
                $attributes[] = '#[WithCast(EnumArrayCast::class, '.$short.'::class)]';
            } else {
                $imports[] = 'Spatie\\LaravelData\\Attributes\\DataCollectionOf';
                $attributes[] = '#[DataCollectionOf('.$short.'::class)]';
            }
        } elseif (isset($items['type'])) {
            $doc = 'array<int, '.scalarPhpType(is_array($items['type']) ? ($items['type'][0] ?? null) : $items['type']).'>';
        }

        return ['php' => applyNullable('array', $nullable), 'doc' => docType(applyNullable($doc, $nullable)), 'imports' => $imports, 'attributes' => $attributes];
    }

    if ($base === 'object') {
        $additional = $property['additionalProperties'] ?? null;
        $valueType = is_array($additional) ? scalarPhpType(is_array($additional['type'] ?? null) ? null : ($additional['type'] ?? null)) : 'mixed';
        $doc = 'array<string, '.$valueType.'>';

        return ['php' => applyNullable('array', $nullable), 'doc' => docType(applyNullable($doc, $nullable)), 'imports' => [], 'attributes' => []];
    }

    return ['php' => applyNullable(scalarPhpType($base), $nullable), 'doc' => null, 'imports' => [], 'attributes' => []];
}

