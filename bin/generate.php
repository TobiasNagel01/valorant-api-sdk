/** Drops the version token from a schema name: AccountV2Response => AccountResponse. */
function stripVersion(string $name): string
{
    return (string) preg_replace('/V[1-9](?=[A-Z]|$)/', '', $name);
}

function isEnumSchema(string $name, array $schemas): bool
{
    return isset($schemas[$name]['enum']);
}

function schemaGroup(string $name): string
{
    foreach (SCHEMA_GROUPS as [$pattern, $group]) {
        if (preg_match($pattern, $name) === 1) {
            return $group;
        }
    }

    throw new RuntimeException("No group configured for schema {$name}");
}

/** Fully qualified class name for a schema: DTOs get a DTO suffix, enums live under Enums\. */
function schemaClass(string $name, array $schemas): string
{
    if (isEnumSchema($name, $schemas)) {
        return NS.'\\Enums\\'.stripVersion($name);
    }

    return NS.'\\DataTransferObjects\\'.schemaGroup($name).'\\'.stripVersion($name).'DTO';
}

function shortClass(string $fqcn): string
{
    $position = strrpos($fqcn, '\\');

    return $position === false ? $fqcn : substr($fqcn, $position + 1);
}

function namespaceOf(string $fqcn): string
{
    $position = strrpos($fqcn, '\\');

    return $position === false ? '' : substr($fqcn, 0, $position);
}

function studly(string $value): string
{
    return str_replace(' ', '', ucwords(str_replace(['_', '-'], ' ', $value)));
}

function camel(string $value): string
{
    return lcfirst(studly($value));
}

/** True when the property name can be used verbatim as a PHP property. */
function isValidIdentifier(string $name): bool
{
    return preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name) === 1;
}

/**
 * Safe PHP name for a JSON key that is not a valid identifier. The spec only has two shapes:
 * clutch counts ("1v1".."1v5") and multi-kill counts ("2k".."5k").
 */
function safePropertyName(string $name): string
{
    if (preg_match('/^\d+v\d+$/', $name) === 1) {
        return 'clutch_'.$name;
    }

    if (preg_match('/^\d+k$/', $name) === 1) {
        return 'multi_kill_'.$name;
    }

    throw new RuntimeException("No safe PHP name configured for property '{$name}'");
}

