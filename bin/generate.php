/**
 * Deletes output from a previous run that this run no longer produces — an endpoint dropped from
 * OPERATIONS, or a schema that fell out of the closure. Only files carrying the generated marker
 * are ever removed, so hand-written classes sitting in the same directories are safe.
 */
$removed = 0;

foreach ([ROOT.'/src/DataTransferObjects', ROOT.'/src/Requests', ROOT.'/src/Enums'] as $directory) {
    if (! is_dir($directory)) {
        continue;
    }

    /** @var iterable<SplFileInfo> $files */
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory, FilesystemIterator::SKIP_DOTS));

    foreach ($files as $file) {
        if ($file->getExtension() !== 'php' || isset($writtenPaths[$file->getRealPath()])) {
            continue;
        }

        if (str_contains((string) file_get_contents($file->getPathname()), MARKER)) {
            unlink($file->getPathname());
            $removed++;
        }
    }
}

foreach (glob(ROOT.'/tests/Fixtures/*.json') ?: [] as $fixture) {
    if (! isset($writtenPaths[realpath($fixture) ?: $fixture])) {
        unlink($fixture);
        $removed++;
    }
}

// Drop directories the sweep emptied.
foreach ([ROOT.'/src/DataTransferObjects', ROOT.'/src/Requests'] as $directory) {
    foreach (glob($directory.'/*', GLOB_ONLYDIR) ?: [] as $group) {
        if ((glob($group.'/*') ?: []) === []) {
            rmdir($group);
        }
    }
}

