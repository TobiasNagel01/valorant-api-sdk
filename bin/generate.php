/**
 * Builds a payload that satisfies a schema: every required key present with a value of the right
 * type, every optional key present as null. Feeding these through the DTOs is what proves the
 * generated types actually match the spec.
 *
 * @param  array<int, string>  $stack  Schema names currently being expanded, to break any cycles.
 */
function sampleFor(array $schema, array $schemas, array $stack = []): mixed
{
    if (isset($schema['$ref'])) {
        $name = refName($schema['$ref']);

        if (isset(UNION_SCHEMAS[$name])) {
            return UNION_SCHEMAS[$name]['php'] === 'mixed' ? null : 'sample';
        }

        if (in_array($name, $stack, true)) {
            return null;
        }

        if (isEnumSchema($name, $schemas)) {
            return $schemas[$name]['enum'][0];
        }

        return sampleFor($schemas[$name], $schemas, [...$stack, $name]);
    }

    if (isset($schema['enum'])) {
        return $schema['enum'][0];
    }

    if (isset($schema['oneOf'])) {
        foreach ($schema['oneOf'] as $variant) {
            if (isset($variant['$ref'])) {
                return sampleFor($variant, $schemas, $stack);
            }
        }

        return null;
    }

    $types = (array) ($schema['type'] ?? []);
    $base = null;

    foreach ($types as $type) {
        if ($type !== 'null') {
            $base = (string) $type;

            break;
        }
    }

    if ($base === 'object' || isset($schema['properties'])) {
        if (! isset($schema['properties'])) {
            return isset($schema['additionalProperties']) ? ['sample' => sampleFor($schema['additionalProperties'], $schemas, $stack)] : [];
        }

        $required = $schema['required'] ?? [];
        $payload = [];

        foreach ($schema['properties'] as $name => $property) {
            $payload[$name] = in_array($name, $required, true)
                ? sampleFor($property, $schemas, $stack)
                : null;
        }

        return $payload;
    }

    return match ($base) {
        'array' => [sampleFor($schema['items'] ?? [], $schemas, $stack)],
        'string' => 'sample',
        'integer' => 1,
        'number' => 1.5,
        'boolean' => true,
        default => null,
    };
}

/** Renders a PHP value using short array syntax, so the generated manifest needs no reformatting. */
function exportPhp(mixed $value, int $depth = 0): string
{
    $pad = str_repeat('    ', $depth + 1);
    $closePad = str_repeat('    ', $depth);

    if (is_array($value)) {
        if ($value === []) {
            return '[]';
        }

        $isList = array_is_list($value);
        $lines = [];

        foreach ($value as $key => $item) {
            $lines[] = $pad.($isList ? '' : var_export((string) $key, true).' => ').exportPhp($item, $depth + 1).',';
        }

        return "[\n".implode("\n", $lines)."\n".$closePad.']';
    }

    return var_export($value, true);
}

