$raw = file_get_contents(ROOT.'/openapi.json');

if ($raw === false) {
    fwrite(STDERR, "Unable to read openapi.json\n");
    exit(1);
}

/** @var array<string, mixed> $spec */
$spec = json_decode($raw, true, 512, JSON_THROW_ON_ERROR);

/** @var array<string, array<string, mixed>> $schemas */
$schemas = $spec['components']['schemas'];

/** @var array<string, array<string, mixed>> $operations operationId => operation, with method/path attached */
$operations = [];

foreach ($spec['paths'] as $path => $item) {
    foreach ($item as $method => $operation) {
        $id = $operation['operationId'] ?? null;

        if (is_string($id) && isset(OPERATIONS[$id])) {
            $operation['__method'] = strtoupper((string) $method);
            $operation['__path'] = (string) $path;
            $operations[$id] = $operation;
        }
    }
}

$missing = array_diff(array_keys(OPERATIONS), array_keys($operations));

if ($missing !== []) {
    fwrite(STDERR, 'Operations missing from the spec: '.implode(', ', $missing)."\n");
    exit(1);
}

